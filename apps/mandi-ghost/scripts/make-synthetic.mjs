#!/usr/bin/env node
// Writes public/snapshot.json: a SYNTHETIC sample (synthetic: true) from a fixed seed. Not real prices.
// Usage: node scripts/make-synthetic.mjs [--now ISO]   (default now = fixed demo date so the file is reproducible)
import { writeFileSync } from 'node:fs';
import { SOURCES, LICENCES, ATTRIBUTION, MARKETS, COMMODITIES } from './common.mjs';

const nowArg = process.argv.indexOf('--now');
const now = new Date(nowArg > 0 ? process.argv[nowArg + 1] : '2026-11-13T06:00:00Z');

let seed = 20261113;
function rnd() { // mulberry32
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

const rows = [];
const weather = {};
for (const [market, m] of Object.entries(MARKETS)) {
  for (const [commodity, base] of Object.entries(COMMODITIES)) {
    let modal = base * (0.9 + rnd() * 0.2);
    for (let back = 9; back >= 0; back--) { // 10 days of history; the app keeps the newest 7
      const day = new Date(now.getTime() - back * 86_400_000).toISOString().slice(0, 10);
      modal = Math.max(base * 0.5, modal * (0.96 + rnd() * 0.09));
      const m0 = Math.round(modal);
      rows.push({
        state: m.state, district: m.district, market, commodity, variety: 'Local', arrival_date: day,
        min_price: Math.round(m0 * 0.88), max_price: Math.round(m0 * 1.12), modal_price: m0,
      });
    }
  }
  weather[market] = [0, 1, 2, 3].map((i) => ({
    date: new Date(now.getTime() + i * 86_400_000).toISOString().slice(0, 10),
    tmax: Math.round(30 + rnd() * 6), tmin: Math.round(20 + rnd() * 4), rain: Math.round(rnd() * 30) / 10,
  }));
}

const snapshot = {
  synthetic: true,
  note: 'SYNTHETIC sample data generated by scripts/make-synthetic.mjs. These are not real mandi prices.',
  generatedAt: now.toISOString(),
  sources: SOURCES, licences: LICENCES, attribution: ATTRIBUTION, droppedRows: 0,
  markets: Object.fromEntries(Object.entries(MARKETS).map(([k, v]) => [k, { lat: v.lat, lon: v.lon }])),
  weather, rows,
};
writeFileSync(new URL('../public/snapshot.json', import.meta.url), JSON.stringify(snapshot) + '\n');
console.log(`snapshot.json: synthetic, ${rows.length} rows`);
