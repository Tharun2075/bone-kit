#!/usr/bin/env node
// Generates tokens.css (the --bk-* custom properties) from BRAND.lock.json. The only place a colour value is written.
// Usage: node scripts/make-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const here = new URL('..', import.meta.url);
const lock = JSON.parse(readFileSync(new URL('BRAND.lock.json', here), 'utf8'));

function block(m, chart) {
  const v = {
    bg: m.bg, surface: m.surface, fg: m.ink, muted: m.muted, border: m.line, accent: m.accent, tint: m.tint,
    'on-accent': m.surface === '#FFFFFF' ? m.surface : m.bg, focus: m.highlight,
    'status-ok': m.success, 'status-warn': m.warn, 'status-off': m.error,
    'on-status': m.surface === '#FFFFFF' ? m.surface : m.bg,
  };
  chart.forEach((c, i) => { v[`chart-${i + 1}`] = c; });
  return Object.entries(v).map(([k, c]) => `  --bk-${k}: ${c};`).join('\n');
}

const css = `/* Generated by scripts/make-tokens.mjs from BRAND.lock.json. Do not edit by hand. */
:root {
${block(lock.light, lock.chart)}
}
@media (prefers-color-scheme: dark) {
  :root {
${block(lock.dark, lock.chart).replace(/^/gm, '  ')}
  }
}
`;
writeFileSync(new URL('tokens.css', here), css);
console.log('tokens.css written');
